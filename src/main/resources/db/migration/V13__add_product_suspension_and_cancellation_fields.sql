-- V13__add_product_suspension_and_cancellation_fields.sql
--
-- Acrescenta, a pedido do usuário (21/09/2026 - ver README, seção "Evoluções
-- pedidas"):
--   * T_PRODUCT.SUSPENSION_STATUS: FK lógica para T_DOMAIN_PRODUCT_SUSPENSION_STATUS
--     (V12) - sempre "1 - Adimplente" na criação (não existe, hoje, nenhum
--     fluxo que venda um produto já inadimplente).
--   * T_PRODUCT.CANCELLATION_CHANNEL / CANCELLATION_EFC_DT / CANCELLATION_STATUS /
--     CANCELLATION_DESCRIPTION / AUTO_CANCEL_SCH_B: detalham o MESMO evento
--     que CANCELLATION_REQ_DT/CANCELLATION_SCH_DT (V9) já registrava - a
--     diferença é que V9 só guardava "quando", e estas 5 colunas novas
--     guardam "quem pediu, por qual canal, com qual status e por que". Ver
--     ProductService.persistProducts: reaproveita EXATAMENTE a mesma
--     condição booleana já usada para preencher CANCELLATION_REQ_DT/
--     CANCELLATION_SCH_DT (feature toggle AUTOMATIC_SCHEDULE_CANCEL_FOR_ONE_SHOT
--     ligada E produto ONESHOT com isExpiriationService=true), então as duas
--     "famílias" de coluna nascem e mudam sempre juntas, nunca em
--     dessincronia.
--
-- BACKFILL sem exigir reset de banco: assim como DISABLE_BILLING_B (V9) foi
-- calculada a partir de TYPE (já existente na própria linha), aqui as 3
-- colunas NOT NULL abaixo são calculadas a partir de CANCELLATION_REQ_DT
-- (também já existente, desde V9): CANCELLATION_REQ_DT IS NULL identifica,
-- sem ambiguidade, exatamente o mesmo "cenário 1" (nenhum cancelamento
-- agendado) descrito no pedido do usuário - o "cenário 2" é o caso oposto.
-- =============================================================================

ALTER TABLE T_PRODUCT
    ADD COLUMN SUSPENSION_STATUS      INT NULL,
    ADD COLUMN CANCELLATION_CHANNEL   VARCHAR(50) NULL,
    ADD COLUMN CANCELLATION_EFC_DT    BIGINT NULL,
    ADD COLUMN CANCELLATION_STATUS    INT NULL,
    ADD COLUMN CANCELLATION_DESCRIPTION VARCHAR(500) NULL,
    ADD COLUMN AUTO_CANCEL_SCH_B      CHAR(1) NULL;

-- "Cenário 1" (sem agendamento): SUSPENSION_STATUS=1, CANCELLATION_CHANNEL=NULL,
-- CANCELLATION_STATUS=1, CANCELLATION_DESCRIPTION=NULL, AUTO_CANCEL_SCH_B=0.
UPDATE T_PRODUCT
SET SUSPENSION_STATUS = 1,
    CANCELLATION_CHANNEL = NULL,
    CANCELLATION_STATUS = 1,
    CANCELLATION_DESCRIPTION = NULL,
    AUTO_CANCEL_SCH_B = '0'
WHERE CANCELLATION_REQ_DT IS NULL;

-- "Cenário 2" (cancelamento agendado): SUSPENSION_STATUS=1, CANCELLATION_CHANNEL=BRS,
-- CANCELLATION_STATUS=2, CANCELLATION_DESCRIPTION=texto fixo, AUTO_CANCEL_SCH_B=1.
UPDATE T_PRODUCT
SET SUSPENSION_STATUS = 1,
    CANCELLATION_CHANNEL = 'BRS',
    CANCELLATION_STATUS = 2,
    CANCELLATION_DESCRIPTION = 'Agendamento automatico por ser produto cm servico sem recorrencia',
    AUTO_CANCEL_SCH_B = '1'
WHERE CANCELLATION_REQ_DT IS NOT NULL;

-- CANCELLATION_EFC_DT nasce sempre NULL em ambos os cenários (só é
-- preenchida quando o cancelamento é de fato EFETIVADO - fora do escopo
-- desta v1, igual já registrado para T_BILL.PAYMENT_DT em V6) - por isso
-- fica de fora do UPDATE acima e continua NULLABLE (não entra no MODIFY
-- NOT NULL abaixo).

ALTER TABLE T_PRODUCT
    MODIFY COLUMN SUSPENSION_STATUS INT NOT NULL,
    MODIFY COLUMN CANCELLATION_STATUS INT NOT NULL,
    MODIFY COLUMN AUTO_CANCEL_SCH_B CHAR(1) NOT NULL;

-- Tabela de auditoria + triggers, sincronizadas com a nova estrutura (ver
-- comentário equivalente em V5__add_product_account_id.sql). As 6 colunas
-- nascem NULLABLE em T_PRODUCT_AU mesmo 3 delas sendo NOT NULL na tabela
-- original - mesmo padrão já usado para DISABLE_BILLING_B em V9.
ALTER TABLE T_PRODUCT_AU
    ADD COLUMN SUSPENSION_STATUS      INT NULL,
    ADD COLUMN CANCELLATION_CHANNEL   VARCHAR(50) NULL,
    ADD COLUMN CANCELLATION_EFC_DT    BIGINT NULL,
    ADD COLUMN CANCELLATION_STATUS    INT NULL,
    ADD COLUMN CANCELLATION_DESCRIPTION VARCHAR(500) NULL,
    ADD COLUMN AUTO_CANCEL_SCH_B      CHAR(1) NULL;

DROP TRIGGER TRG_T_PRODUCT_AU_UPD;
DROP TRIGGER TRG_T_PRODUCT_AU_DEL;

