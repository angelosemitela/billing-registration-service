    VALUES (CAST(UNIX_TIMESTAMP(NOW(3)) * 1000 AS UNSIGNED), 'UPDATE', OLD.ID, OLD.CREATED_DT, OLD.MODIFIED_DT, OLD.ACCOUNT_ID, OLD.PRODUCT_ID, OLD.NAME, OLD.TYPE, OLD.EXP_SERV_B, OLD.RECURRENCE_FREQUENCY, OLD.VALUE, OLD.CURRENCY, OLD.TRIAL_B, OLD.TRIAL_DAYS, OLD.ASSET_ID, OLD.NEXT_BILL_DT, OLD.FUTURE_BILL_DT, OLD.CYCLE_START_DT, OLD.CYCLE_END_DT, OLD.DEFAULT_PAYMENT_ID, OLD.CHANNEL, OLD.TRANSACTION_DT, OLD.STATUS, OLD.DISABLE_BILLING_B, OLD.CANCELLATION_REQ_DT, OLD.CANCELLATION_SCH_DT, OLD.SUSPENSION_STATUS, OLD.CANCELLATION_CHANNEL, OLD.CANCELLATION_EFC_DT, OLD.CANCELLATION_STATUS, OLD.CANCELLATION_DESCRIPTION, OLD.AUTO_CANCEL_SCH_B);
END$$
DELIMITER ;

